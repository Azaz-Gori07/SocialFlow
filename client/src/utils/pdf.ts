/**
 * Dependency-free PDF writer for the analytics report.
 *
 * The previous "Export PDF" button handed the browser a CSV blob with a .pdf
 * name, so the download could never open. This builds a real PDF 1.4 document
 * (Helvetica text, paginated) from the same data the dashboard renders.
 */

type PdfLine = string;

const PAGE_WIDTH = 612;
const PAGE_HEIGHT = 792;
const MARGIN_X = 50;
const TOP_Y = 742;
const LEADING = 12;
const LINES_PER_PAGE = 54;

const escapePdfText = (value: string): string =>
  value
    .replace(/[^\x20-\x7E]/g, '-')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');

const pad = (value: string | number, width: number): string =>
  String(value ?? '').slice(0, width).padEnd(width, ' ');

const num = (value: any): string => {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed.toLocaleString('en-US') : '0';
};

const buildLines = (input: AnalyticsPdfInput): PdfLine[] => {
  const generatedAt = new Date().toLocaleString('en-US', { timeZone: 'UTC' });
  const overview = input.overview || {};
  const growth = Array.isArray(input.growth) ? input.growth : [];
  const platforms = Array.isArray(input.platforms) ? input.platforms : [];

  const lines: PdfLine[] = [
    `SocialFlow Analytics Report`,
    `Generated: ${generatedAt} UTC`,
    `Workspace: ${input.workspaceName || 'Workspace'}    Range: ${input.range || 'All time'}`,
    '',
    'SUMMARY',
    `  Total audience:    ${num(overview.totalFollowers)}`,
    `  Reach:             ${num(overview.totalReach)}`,
    `  Impressions:       ${num(overview.totalImpressions)}`,
    `  Engagement:        ${num(overview.totalEngagement)}`,
    `  Outbound clicks:   ${num(overview.totalClicks)}`,
    `  Average CTR:       ${(Number(overview.averageCtr) || 0).toFixed(2)}%`,
    ''
  ];

  if (growth.length === 0) {
    lines.push('No analytics history has been synced yet.');
  } else {
    lines.push('GROWTH TIMELINE');
    lines.push(
      `${pad('Date', 14)}${pad('Followers', 12)}${pad('Reach', 12)}${pad('Impressions', 14)}${pad('Engagement', 13)}Clicks`
    );
    for (const point of growth.slice(0, 180)) {
      lines.push(
        `${pad(point.date, 14)}${pad(num(point.followers), 12)}${pad(num(point.reach), 12)}${pad(
          num(point.impressions),
          14
        )}${pad(num(point.engagement), 13)}${num(point.clicks)}`
      );
    }
  }

  lines.push('', 'PLATFORM BREAKDOWN');
  if (platforms.length === 0) {
    lines.push('No connected platforms reported metrics.');
  } else {
    lines.push(
      `${pad('Platform', 14)}${pad('Accounts', 10)}${pad('Followers', 12)}${pad('Reach', 12)}${pad(
        'Impressions',
        14
      )}Engagement`
    );
    for (const platform of platforms) {
      lines.push(
        `${pad(platform.platform, 14)}${pad(num(platform.accountsCount), 10)}${pad(
          num(platform.followers),
          12
        )}${pad(num(platform.reach), 12)}${pad(num(platform.impressions), 14)}${num(platform.engagement)}`
      );
    }
  }

  lines.push('', 'Generated by SocialFlow. Metrics come from connected provider analytics and webhooks.');
  return lines;
};

const contentStream = (lines: PdfLine[], firstPage: boolean): string => {
  const commands: string[] = ['BT'];
  if (firstPage) {
    commands.push('/F2 16 Tf', `${MARGIN_X} ${TOP_Y} Td`, `(${escapePdfText(lines[0])}) Tj`, '/F1 9 Tf', `${LEADING} TL`, 'T*');
    for (const line of lines.slice(1)) {
      commands.push(`(${escapePdfText(line)}) Tj`, 'T*');
    }
  } else {
    commands.push(`/F1 9 Tf`, `${MARGIN_X} ${TOP_Y} Td`, `${LEADING} TL`);
    for (const line of lines) {
      commands.push(`(${escapePdfText(line)}) Tj`, 'T*');
    }
  }
  commands.push('ET');
  return commands.join('\n');
};

export interface AnalyticsPdfInput {
  overview?: any;
  growth?: any[];
  platforms?: any[];
  range?: string;
  workspaceName?: string;
}

export const buildAnalyticsPdf = (input: AnalyticsPdfInput): Blob => {
  const lines = buildLines(input);
  const pages: PdfLine[][] = [];
  for (let index = 0; index < lines.length; index += LINES_PER_PAGE) {
    pages.push(lines.slice(index, index + LINES_PER_PAGE));
  }
  if (pages.length === 0) pages.push(['SocialFlow Analytics Report']);

  const pageObjectStart = 5;
  const contentObjectStart = pageObjectStart + pages.length;
  const pageIds = pages.map((_, index) => pageObjectStart + index);
  const contentIds = pages.map((_, index) => contentObjectStart + index);

  const objects: Record<number, string> = {
    1: '<< /Type /Catalog /Pages 2 0 R >>',
    2: `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pages.length} >>`,
    3: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    4: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>'
  };

  pages.forEach((pageLines, index) => {
    const stream = contentStream(pageLines, index === 0);
    objects[pageIds[index]] =
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] ` +
      `/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentIds[index]} 0 R >>`;
    objects[contentIds[index]] = `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`;
  });

  const maxObjectId = contentObjectStart + pages.length - 1;
  let pdf = '%PDF-1.4\n';
  const offsets: number[] = new Array(maxObjectId + 1).fill(0);

  for (let id = 1; id <= maxObjectId; id += 1) {
    offsets[id] = pdf.length;
    pdf += `${id} 0 obj\n${objects[id]}\nendobj\n`;
  }

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${maxObjectId + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let id = 1; id <= maxObjectId; id += 1) {
    pdf += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${maxObjectId + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
};

export const downloadAnalyticsPdf = (input: AnalyticsPdfInput): void => {
  const blob = buildAnalyticsPdf(input);
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `SocialFlow_Analytics_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
};
